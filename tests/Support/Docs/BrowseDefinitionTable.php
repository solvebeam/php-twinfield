<?php

declare(strict_types=1);

namespace SolveBeam\Twinfield\Tests\Support\Docs;

use DOMDocument;
use RuntimeException;
use SolveBeam\Twinfield\BrowseData\BrowseDefinition;
use SolveBeam\Twinfield\BrowseData\BrowseDefinitionColumn;
use SolveBeam\Twinfield\BrowseData\BrowseField;
use SolveBeam\Twinfield\BrowseData\BrowseFieldOption;
use SolveBeam\Twinfield\ProcessXml\ProcessXmlResult;
use SolveBeam\Twinfield\ProcessXml\XmlElement;
use SolveBeam\Twinfield\Tests\Support\TestTokens;

/**
 * The "Fields" section of a browse code example: all fields of the browse definition in
 * `browse-definitions/`, read with the SDK, with the data type and values from `browsefields.xml`.
 */
final class BrowseDefinitionTable
{
    /** @var array<string, BrowseField>|null */
    private static ?array $fields = null;

    public static function section(string $code): string
    {
        $definition = self::definition($code);
        $fields = self::fields();

        $lines = [
            '## Fields',
            '',
            '<!-- Generated by `composer docs:xml` from browse-definitions/, do not edit. -->',
            '',
            sprintf(
                'All fields of the browse definition ([`browse-definitions/%s.xml`](%s)), with the label for a'
                . ' Dutch user, the data type and the values of a field with a fixed list (`browsefields.xml`).'
                . ' A field that is not visible is meant as criterion: asking for it as column can give a server'
                . ' error. Twinfield does not apply the proposed values: send every criterion you need.',
                $code,
                '../../../browse-definitions/' . $code . '.xml',
            ),
            '',
            '| Field | Label | Type | Visible | Criterion |',
            '|---|---|---|---|---|',
        ];

        foreach ($definition->columns as $column) {
            $field = $fields[$column->field] ?? null;

            $lines[] = sprintf(
                '| `%s` | %s | %s | %s | %s |',
                $column->field,
                self::escape($column->label),
                $field === null ? '–' : self::type($field),
                $column->visible ? 'yes' : 'no',
                self::criterion($column),
            );
        }

        return implode("\n", $lines);
    }

    private static function type(BrowseField $field): string
    {
        if ($field->options === []) {
            return $field->dataType->value;
        }

        $values = array_map(
            static fn (BrowseFieldOption $option): string => '`' . $option->value . '`',
            $field->options,
        );

        return $field->dataType->value . ': ' . implode(', ', $values);
    }

    private static function criterion(BrowseDefinitionColumn $column): string
    {
        if (!$column->ask) {
            return '';
        }

        $proposed = array_filter([$column->from, $column->to], static fn (?string $value): bool => $value !== null);

        if ($proposed === []) {
            return '`' . $column->operator->value . '`';
        }

        return sprintf('`%s` (proposed `%s`)', $column->operator->value, implode('` … `', $proposed));
    }

    private static function escape(string $text): string
    {
        return $text === '' ? '–' : str_replace('|', '\|', $text);
    }

    private static function definition(string $code): BrowseDefinition
    {
        $file = self::dir() . '/' . $code . '.xml';

        if (!is_file($file)) {
            throw new RuntimeException(sprintf('No browse definition %s.', $file));
        }

        $result = ProcessXmlResult::fromXml((string) file_get_contents($file));

        return BrowseDefinition::fromXml(XmlElement::root($result), TestTokens::company('1000'));
    }

    /**
     * @return array<string, BrowseField>
     */
    private static function fields(): array
    {
        if (self::$fields !== null) {
            return self::$fields;
        }

        $document = new DOMDocument();

        if (!$document->load(self::dir() . '/browsefields.xml') || $document->documentElement === null) {
            throw new RuntimeException('Cannot read browsefields.xml.');
        }

        $fields = [];

        foreach ((new XmlElement($document->documentElement, 'browsefields'))->list('browsefield') as $element) {
            $field = BrowseField::fromXml($element);
            $fields[$field->code] = $field;
        }

        return self::$fields = $fields;
    }

    private static function dir(): string
    {
        return dirname(__DIR__, 3) . '/browse-definitions';
    }
}
