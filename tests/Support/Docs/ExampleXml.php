<?php

declare(strict_types=1);

namespace SolveBeam\Twinfield\Tests\Support\Docs;

use DOMComment;
use DOMDocument;
use DOMElement;
use DOMXPath;
use Nyholm\Psr7\Factory\Psr17Factory;
use Psr\Http\Message\RequestInterface;
use RuntimeException;
use SolveBeam\Twinfield\Tests\Support\Http\ReplayClient;
use SolveBeam\Twinfield\Tests\Support\TestTokens;
use SolveBeam\Twinfield\Twinfield;

/**
 * Writes the request and response XML of the examples into their README, like the "XML
 * example" of the Twinfield documentation, so readers see how the SDK wraps the web services.
 *
 * The calls run offline against the fixtures, so the XML is what the SDK really sends.
 * `composer docs:xml` updates the READMEs; ExampleXmlTest checks that they are up to date.
 */
final class ExampleXml
{
    private const SOAP_NS = 'http://schemas.xmlsoap.org/soap/envelope/';
    private const TWINFIELD_NS = 'http://www.twinfield.com/';

    private const LINK_START = '<!-- twinfield-documentation:start -->';
    private const LINK_END = '<!-- twinfield-documentation:end -->';
    private const XML_START = '<!-- xml:start -->';
    private const XML_END = '<!-- xml:end -->';

    /** Classes the code of the definitions can use without namespace. */
    private const IMPORTS = [
        'SolveBeam\Twinfield\BankTransaction\BankTransactionInput',
        'SolveBeam\Twinfield\CashTransaction\CashTransactionInput',
        'SolveBeam\Twinfield\ElectronicBankStatement\ElectronicBankStatementInput',
        'SolveBeam\Twinfield\JournalTransaction\JournalTransactionInput',
        'SolveBeam\Twinfield\Period\Period',
        'SolveBeam\Twinfield\PurchaseTransaction\PurchaseTransactionInput',
        'SolveBeam\Twinfield\SalesInvoice\PaymentMethod',
        'SolveBeam\Twinfield\SalesInvoice\SalesInvoiceInput',
        'SolveBeam\Twinfield\SalesTransaction\SalesTransactionInput',
    ];

    public static function examplesDir(): string
    {
        return dirname(__DIR__, 3) . '/examples';
    }

    /**
     * The README of an example with up-to-date sections.
     */
    public static function readme(string $example, string $readme): string
    {
        $pages = ExampleXmlDefinitions::pages();
        $directory = explode('/', $example)[0];

        if (!isset($pages[$directory])) {
            throw new RuntimeException(sprintf('No Twinfield documentation page for %s.', $directory));
        }

        [$title, $url] = $pages[$directory];
        $link = sprintf('Twinfield documentation: [%s](%s).', $title, $url);

        $readme = self::replaceBlock($readme, self::LINK_START, self::LINK_END, $link, self::afterFirstParagraph(...));

        return self::replaceBlock(
            $readme,
            self::XML_START,
            self::XML_END,
            self::section(ExampleXmlDefinitions::examples()[$example] ?? [], $title),
            static fn (string $readme, string $block): string => rtrim($readme) . "\n\n" . $block . "\n",
        );
    }

    /**
     * @param list<XmlExample> $calls
     */
    public static function section(array $calls, string $page): string
    {
        if ($calls === []) {
            throw new RuntimeException('An example needs at least one call.');
        }

        $parts = [
            '## XML',
            '',
            '<!-- Generated by `composer docs:xml` from tests/Support/Docs/ExampleXmlDefinitions.php, do not edit. -->',
            '',
            'What the SDK sends to Twinfield and what Twinfield sends back, for a call like the one in this example. '
            . 'The responses come from the tests, with example data.',
        ];

        foreach ($calls as $call) {
            $parts = [...$parts, '', ...self::call($call, $page)];
        }

        return implode("\n", $parts);
    }

    /**
     * @return list<string>
     */
    private static function call(XmlExample $call, string $page): array
    {
        $http = new ReplayClient(...array_map(ReplayClient::response(...), $call->fixtures));
        $psr17 = new Psr17Factory();
        $twinfield = Twinfield::create(TestTokens::provider('https://example.test'), $http, $psr17, $psr17)
            ->company('1000');

        self::run($call->code, $twinfield);

        if (count($http->requests) !== count($call->fixtures)) {
            throw new RuntimeException(sprintf(
                '"%s" sent %d request(s) for %d fixture(s).',
                $call->title,
                count($http->requests),
                count($call->fixtures),
            ));
        }

        $request = $http->lastRequest();
        $fixture = $call->fixtures[count($call->fixtures) - 1];
        [$requestXml, $isProcessXml] = self::requestXml($request);
        $service = basename($request->getUri()->getPath());

        $lines = [
            '### ' . $call->title,
            '',
            sprintf('Twinfield documentation: [%s: %s](%s).', $page, $call->title, $call->documentation),
            '',
            '```php',
            trim($call->code),
            '```',
            '',
            $isProcessXml
                ? sprintf('The SDK sends this XML as `xmlRequest` of `ProcessXmlString` to `%s`:', $service)
                : sprintf(
                    'The SDK sends this in the SOAP body to `%s`, with SOAPAction `%s`; the access token goes in the SOAP header:',
                    $service,
                    trim($request->getHeaderLine('SOAPAction'), '"'),
                ),
            '',
            '```xml',
            $requestXml,
            '```',
            '',
        ];

        if (!$call->showResponse) {
            return [...$lines, $call->responseNote ?? throw new RuntimeException(sprintf(
                '"%s" hides the response without a note.',
                $call->title,
            ))];
        }

        $responseXml = self::responseXml($fixture, $call->limit);

        if ($responseXml === null) {
            return [...$lines, 'Twinfield answers with an empty SOAP body: the command succeeded.'];
        }

        return [
            ...$lines,
            $isProcessXml ? 'Twinfield answers with this XML in `ProcessXmlStringResult`:' : 'Twinfield answers with this SOAP body:',
            '',
            '```xml',
            $responseXml,
            '```',
            ...($call->responseNote === null ? [] : ['', $call->responseNote]),
        ];
    }

    private static function run(string $code, Twinfield $twinfield): void
    {
        $imports = implode('', array_map(static fn (string $class): string => "use {$class};\n", self::IMPORTS));

        // Runs the code that is also shown, so the README can't show other code than what sent the XML.
        (static function (Twinfield $twinfield) use ($imports, $code): void {
            eval($imports . $code);
        })($twinfield);
    }

    /**
     * @return array{string, bool} The XML, and whether it is a ProcessXml request.
     */
    private static function requestXml(RequestInterface $request): array
    {
        $xpath = self::xpath((string) $request->getBody());
        $xmlRequest = self::first($xpath, '//tw:ProcessXmlString/tw:xmlRequest');

        if ($xmlRequest !== null) {
            return [self::format($xmlRequest->textContent, null), true];
        }

        $body = self::bodyElement($xpath) ?? throw new RuntimeException('The request has an empty SOAP body.');

        return [self::formatElement($body, null), false];
    }

    private static function responseXml(string $fixture, ?int $limit): ?string
    {
        $file = dirname(__DIR__, 2) . '/Fixtures/soap/' . $fixture . '.xml';
        $xpath = self::xpath((string) file_get_contents($file));
        $result = self::first($xpath, '//tw:ProcessXmlStringResult');

        if ($result !== null) {
            return self::format($result->textContent, $limit);
        }

        $body = self::bodyElement($xpath);

        return $body === null ? null : self::formatElement($body, $limit);
    }

    private static function xpath(string $xml): DOMXPath
    {
        $document = new DOMDocument();
        $document->preserveWhiteSpace = false;

        if (!$document->loadXML($xml)) {
            throw new RuntimeException('Not valid XML.');
        }

        $xpath = new DOMXPath($document);
        $xpath->registerNamespace('soap', self::SOAP_NS);
        $xpath->registerNamespace('tw', self::TWINFIELD_NS);

        return $xpath;
    }

    private static function bodyElement(DOMXPath $xpath): ?DOMElement
    {
        return self::first($xpath, '/soap:Envelope/soap:Body/*[1]');
    }

    private static function first(DOMXPath $xpath, string $expression): ?DOMElement
    {
        $node = $xpath->query($expression);
        $element = $node === false ? null : $node->item(0);

        return $element instanceof DOMElement ? $element : null;
    }

    private static function format(string $xml, ?int $limit): string
    {
        $document = new DOMDocument();
        $document->preserveWhiteSpace = false;

        if (!$document->loadXML($xml) || !$document->documentElement instanceof DOMElement) {
            throw new RuntimeException('Not valid XML.');
        }

        return self::formatElement($document->documentElement, $limit);
    }

    private static function formatElement(DOMElement $element, ?int $limit): string
    {
        $document = new DOMDocument('1.0', 'UTF-8');
        $document->formatOutput = true;
        $root = $document->importNode($element, true);
        $document->appendChild($root);

        if ($limit !== null && $root instanceof DOMElement) {
            self::limit($root, $limit);
        }

        return (string) $document->saveXML($root);
    }

    /**
     * Keeps the first elements of a list, with a comment that says how many are left out.
     */
    private static function limit(DOMElement $element, int $limit): void
    {
        $seen = [];
        $removed = [];

        foreach (iterator_to_array($element->childNodes) as $child) {
            if (!$child instanceof DOMElement) {
                continue;
            }

            $seen[$child->nodeName] = ($seen[$child->nodeName] ?? 0) + 1;

            if ($seen[$child->nodeName] > $limit) {
                $removed[$child->nodeName][] = $child;

                continue;
            }

            self::limit($child, $limit);
        }

        foreach ($removed as $name => $children) {
            $comment = new DOMComment(sprintf(' %d more %s elements ', count($children), $name));
            $children[0]->parentNode?->insertBefore($comment, $children[0]);

            foreach ($children as $child) {
                $child->parentNode?->removeChild($child);
            }
        }
    }

    /**
     * @param callable(string, string): string $insert Adds the block when the README has none yet.
     */
    private static function replaceBlock(string $readme, string $start, string $end, string $content, callable $insert): string
    {
        $block = $start . "\n" . $content . "\n" . $end;
        $pattern = '~' . preg_quote($start, '~') . '.*?' . preg_quote($end, '~') . '~s';

        if (preg_match($pattern, $readme) === 1) {
            return (string) preg_replace_callback($pattern, static fn (): string => $block, $readme, 1);
        }

        return $insert($readme, $block);
    }

    /**
     * After the first paragraph: that one is the description of the docs page.
     */
    private static function afterFirstParagraph(string $readme, string $block): string
    {
        if (preg_match('~\A# [^\n]+\n\n.+?\n\n~s', $readme, $match) !== 1) {
            throw new RuntimeException('The README has no title and first paragraph.');
        }

        return $match[0] . $block . "\n\n" . substr($readme, strlen($match[0]));
    }
}
